"""LTX-Video image-to-video skill.

Generates a short video from a static image (optionally guided by a text
prompt) using Lightricks' LTX-Video 0.9.8 13B distilled model.

Runs each stage of generation (text encoding, denoising, safety-screening +
export) in its own short-lived subprocess. On macOS, only *process exit*
reliably returns a component's resident memory to the OS -- there is no
in-process call that does the same. Manual reclamation calls such as
del, gc.collect(), and torch.mps.empty_cache() are deliberately not used
anywhere in this file: process exit is unconditional, complete, and free,
so those calls would only run microseconds before the process dies anyway.
That is why the three stages are three separate OS processes rather than
three phases of one long-lived one.

Why this exists (2026-08-25 incident):
An earlier revision of this module loaded the whole pipeline in a single
process and relied on diffusers' enable_model_cpu_offload()
(shuffling submodules between "cpu" and "mps" on demand) to keep the model
resident under the MPS ceiling. On Apple Silicon that helper is a no-op for
total DRAM *residency*: CPU and GPU share one physical memory pool, so
changing which device owns a tensor changes bookkeeping, not occupancy.
Combined with PyTorch's default MPS high watermark ratio of 1.7 -- which
permits 1.7 x 37.44 GiB = 63.65 GiB of allocation on this 48 GiB host -- the
process was free to keep growing until the machine froze hard, requiring a
forced reboot.

The old docstring's memory numbers were also wrong. Measured, correct
figures:

    component                    on-disk    on-disk dtype   resident @ bf16
    transformer (13.043B params)  24.29 GiB  BF16            24.29 GiB
    text_encoder / T5 (4.762B)    17.74 GiB  F32              8.87 GiB
    vae (1.247B params)            2.32 GiB  BF16             2.32 GiB
    total                         44.36 GiB                  35.48 GiB

35.48 GiB does fit under the 37.44 GiB MPS ceiling, but that leaves only
1.96 GiB for activations and roughly 12.5 GiB for the OS -- too tight for a
single process holding all three components at once. Splitting the work
into stage1 (text encoder only, 8.87 GiB), stage2 (transformer + vae, 26.61
GiB, no text encoder ever loaded), and stage3 (no diffusion weights at all)
means each process's peak footprint is far below the combined figure, and
each one's memory is unconditionally returned to the OS the moment it exits.

Works on Apple Silicon (MPS) and falls back to CPU. CUDA is used if present.

Usage:
    python3 ltx_video_skill.py <image_path> ["<prompt>"] [output_path]

    # or as a module:
    from ltx_video_skill import generate_video
    frames = generate_video("robot.png", "the robot waves", output_path="robot.mp4")

Environment:
    HF_TOKEN  Hugging Face access token (optional; omitted falls back to any
              token cached locally by `huggingface-cli login`, or anonymous
              access for public repos).

Generated output is screened by content_safety.assert_frames_safe (on a
sample of frames) before being saved or returned; a positive verdict raises
ContentSafetyError and saves nothing.

This module intentionally does not import torch, diffusers, transformers,
or content_safety at import time -- those imports, and all model loading,
happen inside the per-stage functions below, each of which only ever runs
inside its own subprocess.
"""

